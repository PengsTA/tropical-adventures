local function IsExtensionStructure(prefab)
	return prefab == "deco_roomglow"
		or prefab == "deco_roomglow_large"
		or string.find(prefab, "cornerbeam", 1, true) ~= nil
		or string.find(prefab, "_beam", 1, true) ~= nil
		or string.find(prefab, "_pillar", 1, true) ~= nil
		or string.find(prefab, "swinging_light", 1, true) ~= nil
		or string.find(prefab, "swinglight", 1, true) ~= nil
end

local function MarkExtensionStructures(layouts)
	for _, layout in pairs(layouts or {}) do
		for _, fixture in ipairs(layout.fixtures or {}) do
			if IsExtensionStructure(fixture.prefab or "") then
				fixture.extension = true
			end
		end
	end
end

