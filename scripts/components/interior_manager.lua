local ROOM_SPACING = 64
local ROOMS_PER_ROW = 32
local ORIGIN_PADDING = 128
local COLLISION_WALL_OUTSET = 0.5
local InteriorRender = require "tools/interior_render"

local function SetRoomExteriorPosition(room, exterior)
    if room == nil or exterior == nil or exterior.Transform == nil then
        return
    end

    local x, _, z = exterior.Transform:GetWorldPosition()
    room.exterior_x = x
    room.exterior_z = z
end

local InteriorManager = Class(function(self, inst)
    self.inst = inst
    self.next_room_id = 0
    self.reusable_room_ids = {}
    self.rooms = {}
    self.room_centers = {}
    -- Keep the logical layout separate from the remote render coordinates.
    -- The extension doors use this persistent graph, while the visual room
    -- shell continues to be generated by the current builder.
    self.room_links = {}

    inst:DoTaskInTime(0, function()
        self:ConfigureRoomRegion()
    end)
end)

function InteriorManager:ConfigureRoomRegion()
    if self.room_region_configured then
        return
    end

    local width, height = TheWorld.Map:GetSize()
    self.origin_x = width * TILE_SCALE / 2 + ORIGIN_PADDING
    self.origin_z = height * TILE_SCALE / 2 + ORIGIN_PADDING
    self.room_region_configured = true
    self:UpdateRenderExtents(self.origin_x, self.origin_z)
end

function InteriorManager:UpdateRenderExtents(x, z)
    InteriorRender.EnsureBounds(x, z)
end

function InteriorManager:GetPositionForId(room_id)
    self:ConfigureRoomRegion()

    local index = room_id - 1
    local x = self.origin_x + (index % ROOMS_PER_ROW) * ROOM_SPACING
    local z = self.origin_z + math.floor(index / ROOMS_PER_ROW) * ROOM_SPACING
    self:UpdateRenderExtents(x, z)
    return x, z
end

function InteriorManager:GetNewRoomId()
    local reusable_id = next(self.reusable_room_ids)
    if reusable_id ~= nil then
        self.reusable_room_ids[reusable_id] = nil
        return reusable_id
    end

    self.next_room_id = self.next_room_id + 1
    return self.next_room_id
end

function InteriorManager:Allocate(owner, kind)
    local room_id = owner ~= nil and owner.interiorID or nil
    if room_id == nil then
        room_id = self:GetNewRoomId()
        if owner ~= nil then
            owner.interiorID = room_id
        end
    elseif room_id > self.next_room_id then
        self.next_room_id = room_id
    end

    local room = self.rooms[room_id]
    if room == nil then
        local x, z = self:GetPositionForId(room_id)
        room = {
            id = room_id,
            x = x,
            z = z,
            kind = kind,
        }
        self.rooms[room_id] = room
    elseif room.kind == nil then
        room.kind = kind
    end

    if room.exterior_x == nil or room.exterior_z == nil then
        SetRoomExteriorPosition(room, owner)
    end

    return room
end

function InteriorManager:GetRoom(room_id)
    return room_id ~= nil and self.rooms[room_id] or nil
end

function InteriorManager:GetRoomAtPoint(x, z)
    for _, room in pairs(self.rooms) do
        if room.width ~= nil and room.depth ~= nil
            and math.abs(x - room.x) <= room.width * 0.5
            and math.abs(z - room.z) <= room.depth * 0.5 then
            return room
        end
    end
    return nil
end

function InteriorManager:IsShopAtPoint(x, z)
    local room = self:GetRoomAtPoint(x, z)
    local kind = room ~= nil and (room.room_template or room.kind) or nil
    return type(kind) == "string" and string.sub(kind, 1, 5) == "shop_"
end

function InteriorManager:RegisterRoomCenter(room_id, center)
    if room_id ~= nil and center ~= nil then
        self.room_centers[room_id] = center
    end
end

function InteriorManager:ConnectRooms(first_room_id, direction, second_room_id)
    if first_room_id == nil or second_room_id == nil or direction == nil then
        return
    end

    local opposite = {
        back = "front",
        front = "back",
        left = "right",
        right = "left",
    }
    local reverse = opposite[direction]
    if reverse == nil then
        return
    end

    self.room_links[first_room_id] = self.room_links[first_room_id] or {}
    self.room_links[second_room_id] = self.room_links[second_room_id] or {}
    self.room_links[first_room_id][direction] = second_room_id
    self.room_links[second_room_id][reverse] = first_room_id
end

function InteriorManager:DisconnectRoom(room_id)
    local links = self.room_links[room_id]
    if links ~= nil then
        for _, other_room_id in pairs(links) do
            local other_links = self.room_links[other_room_id]
            if other_links ~= nil then
                for direction, linked_room_id in pairs(other_links) do
                    if linked_room_id == room_id then
                        other_links[direction] = nil
                    end
                end
            end
        end
    end
    self.room_links[room_id] = nil
end

function InteriorManager:RevealRoom(room_id)
    local center = room_id ~= nil and self.room_centers[room_id] or nil
    if center ~= nil and center:IsValid() and center.SetExplored ~= nil then
        center:SetExplored()
    end
end

function InteriorManager:BuildPlayerHouse(exterior, layout)
    local rooms = {}
    local house_id = exterior.interiorID

    for index, definition in ipairs(layout.rooms) do
        local owner = index == 1 and exterior or nil
        local room = self:Allocate(owner, "player_house")
        local size = layout.sizes ~= nil and layout.sizes[definition.kind] or nil
        size = size or definition
        if house_id == nil then
            house_id = room.id
        end

        room.house_id = house_id
        SetRoomExteriorPosition(room, exterior)
        room.layout_key = definition.key
        room.width = definition.width or size.width
        room.depth = definition.depth or size.depth
        room.reference_width = definition.reference_width or size.reference_width or room.width
        room.reference_depth = definition.reference_depth or size.reference_depth or room.depth
        room.map_x = definition.map_x
        room.map_z = definition.map_z
        rooms[definition.key] = room
    end

    return rooms
end

function InteriorManager:BuildForExterior(exterior, builder_prefab)
    assert(exterior ~= nil and exterior:IsValid(), "a valid exterior is required")
    assert(self.pending_exterior == nil, "nested room generation is not supported")

    self.pending_exterior = exterior
    local builder = SpawnPrefab(builder_prefab)
    self.pending_exterior = nil
    assert(builder ~= nil, "missing room builder prefab: " .. tostring(builder_prefab))
    return builder
end

function InteriorManager:ConsumePendingExterior()
    local exterior = self.pending_exterior
    assert(exterior ~= nil and exterior:IsValid(), "room builders must be created by interior_manager")
    return exterior
end

function InteriorManager:Release(room_id)
    if room_id ~= nil then
        self:DisconnectRoom(room_id)
        self.rooms[room_id] = nil
        self.room_centers[room_id] = nil
        self.reusable_room_ids[room_id] = true
    end
end

function InteriorManager:SpawnPerimeter(room, prefab, half_width, half_depth)
    local parts = {}
    -- Keep invisible collision outside the rendered shell. This leaves a
    -- one-unit buffer at every edge without changing room bounds or visuals.
    half_width = half_width + COLLISION_WALL_OUTSET
    half_depth = half_depth + COLLISION_WALL_OUTSET
    for x = -half_width, half_width do
        for z = -half_depth, half_depth do
            if x == -half_width or x == half_width or z == -half_depth or z == half_depth then
                local part = SpawnPrefab(prefab)
                if part ~= nil then
                    part.Transform:SetPosition(room.x + x, 0, room.z + z)
                    table.insert(parts, part)
                end
            end
        end
    end
    return parts
end

function InteriorManager:OnSave()
    return {
        next_room_id = self.next_room_id,
        reusable_room_ids = self.reusable_room_ids,
        rooms = self.rooms,
        room_links = self.room_links,
    }
end

function InteriorManager:OnLoad(data)
    if data == nil then
        return
    end

    self.next_room_id = data.next_room_id or self.next_room_id
    self.reusable_room_ids = data.reusable_room_ids or self.reusable_room_ids
    self.rooms = data.rooms or self.rooms
    self.room_links = data.room_links or self.room_links
    self:ConfigureRoomRegion()
    for _, room in pairs(self.rooms) do
        self:UpdateRenderExtents(room.x, room.z)
    end
end

return InteriorManager
